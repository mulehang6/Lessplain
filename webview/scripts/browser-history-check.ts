import assert from "node:assert/strict";
import type { Snapshot, View } from "../src/runtime/types";
import { fit, harness, node, readyCanvas, viewport } from "./browser-harness";

/** 复现用户截图的旧容器结构，不依赖先把历史记录重写成 Board。 */
export async function checkHistoryAndPopups(h: Awaited<ReturnType<typeof harness>>, snapshot: Snapshot, redis: View) {
  const { page, calls, publish } = h;
  const document = structuredClone(redis.document);
  document.spec.root = "old-root";
  document.spec.elements["old-root"] = { type: "Stack", props: {}, children: ["old-intro", "old-grid"] };
  document.spec.elements["old-intro"] = { type: "Text", props: { text: "旧历史里的普通说明组件" } };
  document.spec.elements["old-grid"] = { type: "Grid", props: { columns: 1 }, children: ["hot-graph", "tag-graph", "rank-graph"] };
  const legacy: View = { ...redis, ref: "view:legacy", document };
  snapshot.views.push(legacy);
  snapshot.browse[legacy.ref] = { "canvas:toolwindow": { trail: [], viewport: { x: 5000, y: 5000, zoom: 1 }, positions: { 'companion/"old-root"': { x: 400, y: 1300 } } } };
  const original = JSON.stringify(legacy);
  await page.setViewportSize({ width: 1080, height: 780 });
  await publish(legacy.ref); await readyCanvas(page);
  assert.equal(await page.locator(".lesson-node").count(), 16);
  assert.equal(await page.locator(".react-flow").count(), 1);
  const firstGraph = (await node(page, "hot-graph", "home").boundingBox())!;
  assert.ok(firstGraph.x >= 0 && firstGraph.y >= 0 && firstGraph.x < 1080 && firstGraph.y < 780, "旧文字组件的镜头不得把恢复后的图留在屏幕外");
  assert.equal(JSON.stringify(legacy), original, "恢复显示不得改写持久记录");
  await fit(page);
  const intro = page.locator('[data-element-id="old-intro"]');
  await intro.hover();
  const icon = intro.getByRole("button", { name: "为组件添加注释", exact: true });
  assert.equal(await icon.innerText(), "", "普通组件也只显示图标");
  assert.equal(await icon.locator("svg").count(), 1);
  await icon.hover(); await page.getByRole("tooltip", { name: "为组件添加注释", exact: true }).waitFor();
  await intro.hover(); await page.waitForTimeout(250);
  assert.equal(await icon.evaluate(el => getComputedStyle(el).pointerEvents), "auto");
  const anchor = (await icon.boundingBox())!;
  await icon.click();
  const popup = page.locator(".annotation-dialog");
  const bounds = (await popup.boundingBox())!;
  assert.ok(bounds.x >= 8 && bounds.x + bounds.width <= 1072 && bounds.y >= 8 && bounds.y + bounds.height <= 772);
  assert.ok(Math.abs(bounds.y - anchor.y - anchor.height - 6) < 2 || Math.abs(bounds.y + bounds.height - anchor.y + 6) < 2, "弹层必须锚在图标附近");
  const marker = "保留组件草稿";
  await page.getByLabel("问题内容").fill(marker);
  await page.keyboard.press("Escape"); await popup.waitFor({ state: "detached" });
  await intro.hover(); await icon.click();
  assert.equal(await page.getByLabel("问题内容").inputValue(), marker);
  await page.getByRole("button", { name: "显示全图", exact: true }).click();
  await popup.waitFor({ state: "detached" });
  // 图内平移把节点放到右下角；键盘入口必须从同一图标的DOM屏幕坐标翻转弹层。
  const target = node(page, "tag-graph", "tag-hit");
  await target.locator(".node-title").click(); await page.waitForTimeout(600);
  await page.locator(".global-canvas-shell").focus();
  await page.mouse.move(80, 70); await page.mouse.down({ button: "right" }); await page.mouse.move(365, 325, { steps: 8 }); await page.mouse.up({ button: "right" });
  await target.hover();
  const annotation = target.getByRole("button", { name: /添加注释/ });
  const nodeAnchor = (await annotation.boundingBox())!;
  await annotation.focus(); await page.keyboard.press("Enter");
  const flipped = (await popup.boundingBox())!;
  assert.ok(flipped.x >= 8 && flipped.x + flipped.width <= 1072 && flipped.y + flipped.height <= 772);
  assert.ok(flipped.y + flipped.height <= nodeAnchor.y - 4, "底部图标必须向上展开");
  assert.equal(await popup.locator("pre").count(), 0);
  await page.getByLabel("问题内容").fill("节点草稿");
  await page.mouse.click(20, 280); await popup.waitFor({ state: "detached" });
  await target.hover(); await annotation.click();
  assert.equal(await page.getByLabel("问题内容").inputValue(), "节点草稿");
  await page.evaluate(() => window.__lessplainReceive?.({ showHistory: true }));
  await popup.waitFor({ state: "detached" });
  await publish(legacy.ref); await readyCanvas(page);
  await fit(page);
  await target.click(); await page.waitForTimeout(600); await target.hover(); await annotation.click();
  assert.equal(await page.getByLabel("问题内容").inputValue(), "节点草稿");
  await page.keyboard.press("Escape");
  await page.evaluate(() => window.__lessplainReceive?.({ showHistory: true }));
  const selectedBefore = calls.filter(call => call.method === "select").length;
  const row = page.locator('.history-row[data-view-ref="view:legacy"]');
  assert.equal(await row.locator("small:not(.unread)").count(), 0, "历史不显示层级序号");
  const normalRow = await row.evaluate(el => getComputedStyle(el).backgroundColor);
  await row.hover();
  assert.notEqual(await row.evaluate(el => getComputedStyle(el).backgroundColor), normalRow, "整行 hover 有明确背景反馈");
  await row.click({ button: "right", position: { x: 120, y: 20 } });
  const menu = page.getByRole("menu", { name: "历史记录菜单", exact: true });
  assert.equal(await menu.getByRole("menuitem").count(), 2);
  assert.equal(await page.getByRole("dialog", { name: "管理问题" }).count(), 0);
  assert.equal(calls.filter(call => call.method === "select").length, selectedBefore);
  await page.keyboard.press("Escape"); await menu.waitFor({ state: "detached" });
  await row.focus(); await page.keyboard.press("Shift+F10");
  await page.getByRole("menuitem", { name: "重命名", exact: true }).click();
  const rename = page.getByRole("dialog", { name: "重命名历史记录", exact: true });
  assert.equal(await rename.locator("input").count(), 1); assert.equal(await rename.locator("select").count(), 0);
  await row.click({ button: "right" });
  await rename.waitFor({ state: "detached" });
  assert.equal(await menu.getByRole("menuitem").count(), 2, "同一行再次右键也必须重新打开菜单");
  await page.getByRole("menuitem", { name: "重命名", exact: true }).click();
  await page.getByLabel("历史记录名称").fill("已改名的历史");
  await page.keyboard.press("Enter"); await rename.waitFor({ state: "detached" });
  assert.equal(calls.findLast(call => call.method === "rename")!.params.ref, legacy.ref);
  assert.equal(calls.filter(call => call.method === "move").length, 0);
  await row.getByText("已改名的历史", { exact: true }).waitFor();
  // 三层删除确认，先取消一次，确认前没有提交delete。
  snapshot.views.push({ ...legacy, ref: "view:legacy-child", parentRef: legacy.ref }, { ...legacy, ref: "view:legacy-grandchild", parentRef: "view:legacy-child" });
  await publish();
  const deletesBefore = calls.filter(call => call.method === "delete").length;
  await row.click({ button: "right" }); await page.getByRole("menuitem", { name: "删除", exact: true }).click();
  const confirm = page.getByRole("dialog", { name: "删除历史记录", exact: true });
  assert.ok((await confirm.innerText()).includes("2 条追问"));
  const confirmationBounds = (await confirm.boundingBox())!;
  assert.ok(Math.abs(confirmationBounds.x + confirmationBounds.width / 2 - 540) < 2 && Math.abs(confirmationBounds.y + confirmationBounds.height / 2 - 390) < 2);
  assert.equal(calls.filter(call => call.method === "delete").length, deletesBefore);
  await confirm.getByRole("button", { name: "取消", exact: true }).click();
  assert.equal(calls.filter(call => call.method === "delete").length, deletesBefore);
  await row.click({ button: "right" }); await page.getByRole("menuitem", { name: "删除", exact: true }).click();
  await confirm.getByRole("button", { name: "确认删除", exact: true }).click(); await confirm.waitFor({ state: "detached" });
  assert.equal(calls.findLast(call => call.method === "delete")!.params.ref, legacy.ref);
  assert.equal(snapshot.views.some(view => view.ref.startsWith("view:legacy")), false);
  assert.ok(snapshot.views.some(view => view.ref === redis.ref), "删除不得波及其他理解树");
  assert.equal(calls.filter(call => call.method === "select").length, selectedBefore);
  // 窄窗纯组件弹层不溢出；菜单也在边缘可见，点击外部立即关闭。
  const simple: View = { ...redis, ref: "view:component", document: { ...redis.document, title: "字段", spec: { root: "text", elements: { text: { type: "Text", props: { text: "字段说明" } } } } } };
  snapshot.views.push(simple); await page.setViewportSize({ width: 320, height: 430 }); await publish(simple.ref);
  await page.getByText("字段说明", { exact: true }).waitFor(); await page.waitForTimeout(500);
  const component = page.locator('.lesson-element[data-element-id="text"]');
  await component.hover(); await component.getByRole("button", { name: "为组件添加注释", exact: true }).click();
  const small = (await popup.boundingBox())!;
  assert.ok(small.x >= 8 && small.y >= 8 && small.x + small.width <= 312 && small.y + small.height <= 422);
  await page.keyboard.press("Escape");
  await page.evaluate(() => window.__lessplainReceive?.({ showHistory: true }));
  await page.locator('.history-row[data-view-ref="view:component"]').focus(); await page.keyboard.press("Shift+F10");
  const menuBounds = (await menu.boundingBox())!;
  assert.ok(menuBounds.x >= 8 && menuBounds.x + menuBounds.width <= 312);
  await page.mouse.click(10, 10); await menu.waitFor({ state: "detached" });
  assert.equal(await viewport(page).count(), 0);
}
